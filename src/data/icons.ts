/**
 * Extracts inner SVG markup by stripping outer <svg> and </svg> tags.
 */
function extractInnerHtml(svg: string): string {
  return svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
}

